create or replace function public.resolver_mi_personal_rrhh()
returns table (
  empresa_id text,
  personal_id text,
  personal_tipo text,
  nombre text,
  documento text,
  email text,
  telefono text,
  cargo text,
  area text,
  sede text,
  fecha_ingreso date,
  fecha_fin_contrato date,
  regimen_jornada text,
  dias_ciclo_trabajo integer,
  dias_ciclo_descanso integer,
  dias_vacaciones_disponibles numeric
)
language sql
security definer
set search_path = public
as $$
  select p.empresa_id, p.id, 'operativo', p.nombre, p.documento, p.email, p.telefono, p.cargo, p.area, p.sede,
         p.fecha_ingreso, p.fecha_fin_contrato, p.regimen_jornada, p.dias_ciclo_trabajo, p.dias_ciclo_descanso, p.dias_vacaciones_disponibles
    from public.personal_operativo p
   where p.auth_user_id::text = auth.uid()::text
      or lower(coalesce(p.email, '')) = lower(coalesce((auth.jwt() ->> 'email'), ''))
  union all
  select p.empresa_id, p.id, 'administrativo', p.nombre, coalesce(p.documento, p.dni), p.email, p.telefono, p.cargo, p.area, p.sede,
         p.fecha_ingreso, p.fecha_fin_contrato, p.regimen_jornada, p.dias_ciclo_trabajo, p.dias_ciclo_descanso, p.dias_vacaciones_disponibles
    from public.personal_administrativo p
   where p.auth_user_id::text = auth.uid()::text
      or lower(coalesce(p.email, '')) = lower(coalesce((auth.jwt() ->> 'email'), ''))
  limit 1;
$$;

create or replace function public.es_mi_personal_rrhh(p_empresa_id text, p_personal_id text)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.resolver_mi_personal_rrhh() f
    where f.empresa_id = p_empresa_id and f.personal_id = p_personal_id
  );
$$;

