create or replace function public.mover_candidatura_rrhh(
  p_candidatura_id text,
  p_etapa text,
  p_motivo text default null,
  p_notas text default null,
  p_personal_id text default null,
  p_personal_tipo text default null
) returns public.rrhh_candidaturas
language plpgsql
security definer
set search_path = public
as $$
declare
  v_old public.rrhh_candidaturas;
  v_new public.rrhh_candidaturas;
begin
  select * into v_old from public.rrhh_candidaturas where id = p_candidatura_id for update;
  if not found then
    raise exception 'Candidatura no encontrada';
  end if;
  if not public.usuario_tiene_empresa(v_old.empresa_id) then
    raise exception 'Sin acceso al tenant';
  end if;
  if p_etapa = 'descartado' and nullif(trim(coalesce(p_motivo, '')), '') is null then
    raise exception 'El descarte requiere motivo';
  end if;

  update public.rrhh_candidaturas
     set etapa = p_etapa,
         notas_evaluacion = coalesce(p_notas, notas_evaluacion),
         descarte_motivo = case when p_etapa = 'descartado' then p_motivo else descarte_motivo end,
         personal_id = coalesce(p_personal_id, personal_id),
         personal_tipo = coalesce(p_personal_tipo, personal_tipo),
         updated_at = now()
   where id = p_candidatura_id
   returning * into v_new;

  insert into public.rrhh_candidatura_historial(empresa_id, candidatura_id, etapa_desde, etapa_hasta, motivo, notas)
  values (v_old.empresa_id, p_candidatura_id, v_old.etapa, p_etapa, p_motivo, p_notas);

  if p_etapa = 'contratado' and v_old.etapa <> 'contratado' then
    update public.rrhh_vacantes
       set posiciones_cubiertas = least(posiciones, posiciones_cubiertas + 1),
           estado = case when posiciones_cubiertas + 1 >= posiciones then 'cerrada' else estado end,
           updated_at = now()
     where id = v_old.vacante_id;
  end if;

  return v_new;
end;
$$;

