create table if not exists public.rrhh_vacantes (
  id text primary key,
  empresa_id text not null references public.empresas(id) on delete cascade,
  cargo_id text,
  cargo text not null,
  area text,
  sede text,
  descripcion text,
  posiciones integer not null default 1 check (posiciones > 0),
  posiciones_cubiertas integer not null default 0 check (posiciones_cubiertas >= 0),
  fecha_apertura date not null default current_date,
  estado text not null default 'abierta' check (estado in ('abierta','en_proceso','cerrada','cancelada')),
  motivo_cancelacion text,
  public_token text unique,
  creado_por text default auth.uid()::text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.rrhh_candidatos (
  id text primary key,
  empresa_id text not null references public.empresas(id) on delete cascade,
  nombre text not null,
  dni text not null,
  telefono text,
  email text,
  cv_url text,
  cv_path text,
  alerta_historial jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (empresa_id, dni)
);

create table if not exists public.rrhh_candidaturas (
  id text primary key,
  empresa_id text not null references public.empresas(id) on delete cascade,
  vacante_id text not null references public.rrhh_vacantes(id) on delete restrict,
  candidato_id text not null references public.rrhh_candidatos(id) on delete restrict,
  etapa text not null default 'postulado' check (etapa in ('postulado','entrevista','evaluacion','seleccionado','contratado','descartado')),
  fuente text not null default 'interno',
  notas_evaluacion text,
  descarte_motivo text,
  personal_id text,
  personal_tipo text check (personal_tipo is null or personal_tipo in ('operativo','administrativo')),
  creado_por text default auth.uid()::text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.rrhh_candidatura_historial (
  id bigint generated by default as identity primary key,
  empresa_id text not null references public.empresas(id) on delete cascade,
  candidatura_id text not null references public.rrhh_candidaturas(id) on delete cascade,
  etapa_desde text,
  etapa_hasta text not null,
  motivo text,
  notas text,
  usuario_id text default auth.uid()::text,
  fecha timestamptz not null default now()
);

create index if not exists idx_rrhh_vacantes_empresa_estado on public.rrhh_vacantes(empresa_id, estado);
create index if not exists idx_rrhh_candidatos_empresa_dni on public.rrhh_candidatos(empresa_id, dni);
create index if not exists idx_rrhh_candidaturas_empresa_vacante on public.rrhh_candidaturas(empresa_id, vacante_id, etapa);
create index if not exists idx_rrhh_candidatura_historial_candidatura on public.rrhh_candidatura_historial(candidatura_id, fecha);

